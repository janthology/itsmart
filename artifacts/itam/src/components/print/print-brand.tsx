import { format } from "date-fns";

/**
 * Shared branding for printed documents (ticket record, asset label).
 *
 * Print views use inline styles (not Tailwind/theme tokens) so output
 * looks identical regardless of the app's light/dark theme, with
 * `.print-area` forcing exact color reproduction. The DOST logo sits on
 * a white tile — the logo's black geometry would vanish on a dark tile
 * on paper.
 */

export const PRINT_BRAND = {
  primary: "#355872",
  primaryDeep: "#22384e",
  accent: "#2f6da3",
  ink: "#1e293b",
  muted: "#64748b",
  faint: "#94a3b8",
  rule: "#e2e8f0",
} as const;

export function PrintLogoTile({ size = 48 }: { size?: number }) {
  return (
    <span
      style={{
        width: size,
        height: size,
        borderRadius: Math.max(6, Math.round(size * 0.22)),
        background: "#ffffff",
        border: "1px solid #d7e1ec",
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        flexShrink: 0,
      }}
    >
      <img
        src="/dostlogo.png"
        alt="Department of Science and Technology logo"
        style={{ width: size * 0.76, height: size * 0.76, objectFit: "contain" }}
      />
    </span>
  );
}

interface PrintBrandHeaderProps {
  /** Right-aligned document type, e.g. "Support Ticket Record". */
  documentType: string;
  documentNote?: string;
}

export function PrintBrandHeader({ documentType, documentNote = "Official document" }: PrintBrandHeaderProps) {
  return (
    <div style={{ marginBottom: 18 }}>
      <div style={{ display: "flex", alignItems: "center", gap: 12 }}>
        <PrintLogoTile size={48} />
        <div style={{ flex: 1, minWidth: 0, lineHeight: 1.1 }}>
          <div
            style={{
              fontSize: 9,
              fontWeight: 700,
              letterSpacing: "0.18em",
              textTransform: "uppercase",
              color: PRINT_BRAND.muted,
            }}
          >
            DOST &middot; Cagayan Valley
          </div>
          <div
            style={{
              marginTop: 3,
              fontSize: 21,
              fontWeight: 800,
              letterSpacing: "-0.02em",
              color: PRINT_BRAND.ink,
            }}
          >
            IT<span style={{ color: PRINT_BRAND.accent }}>SMART</span>
          </div>
          <div style={{ marginTop: 3, fontSize: 9, color: PRINT_BRAND.faint }}>
            Information Technology Service Management &amp; Asset Registry
          </div>
        </div>
        <div style={{ textAlign: "right", lineHeight: 1.3, flexShrink: 0 }}>
          <div
            style={{
              fontSize: 10,
              fontWeight: 700,
              letterSpacing: "0.12em",
              textTransform: "uppercase",
              color: PRINT_BRAND.primary,
            }}
          >
            {documentType}
          </div>
          <div style={{ fontSize: 9, color: PRINT_BRAND.faint }}>{documentNote}</div>
        </div>
      </div>
      <div
        style={{
          marginTop: 12,
          height: 3,
          borderRadius: 2,
          background: `linear-gradient(90deg, ${PRINT_BRAND.primary} 0%, #7aaace 100%)`,
        }}
      />
    </div>
  );
}

interface PrintBrandFooterProps {
  printedAt: Date;
}

export function PrintBrandFooter({ printedAt }: PrintBrandFooterProps) {
  return (
    <div
      style={{
        marginTop: 24,
        borderTop: `1px solid ${PRINT_BRAND.rule}`,
        paddingTop: 8,
        display: "flex",
        justifyContent: "space-between",
        gap: 12,
        fontSize: 10,
        color: PRINT_BRAND.faint,
      }}
    >
      <span>Generated by ITSMART &middot; DOST &middot; Cagayan Valley</span>
      <span>
        Printed on {format(printedAt, "MMMM d, yyyy h:mm a")} &middot; For official use
      </span>
    </div>
  );
}
